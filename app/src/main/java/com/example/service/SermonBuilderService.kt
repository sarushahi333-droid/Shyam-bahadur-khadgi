package com.example.service

import com.example.data.model.SermonOutline

object SermonBuilderService {

    data class SermonPreset(
        val topicName: String,
        val defaultPassage: String,
        val defaultTitle: String
    )

    val availableTopics = listOf(
        SermonPreset("विश्वासको विजय (Victory of Faith)", "हिब्रू ११:१-६, १ यूहन्ना ५:४", "संसारमाथि विजय प्राप्त गर्ने अटुट विश्वास"),
        SermonPreset("परमेश्वरको अनन्त अनुग्रह (Eternal Grace)", "एफिसी २:१-१०, तीतस २:११-१४", "परमेश्वरको अद्‍भूत अनुग्रह: पापीको उद्धार र नयाँ जीवन"),
        SermonPreset("प्रार्थनाको सामर्थ्य (Power of Prayer)", "फिलिप्पी ४:६-७, याकूब ५:१३-१८", "प्रार्थना: स्वर्गको ढोका खोल्ने र परिस्थिति बदल्ने साँचो सामर्थ्य"),
        SermonPreset("हृदयको साँचो क्षमा (Heartfelt Forgiveness)", "कलस्सी ३:१२-१४, मत्ती १८:२१-३५", "क्रूसको क्षमा: तीतोपनाको बन्धनबाट साँचो मुक्ति"),
        SermonPreset("पवित्र आत्माको अगुवाइ (Led by the Spirit)", "रोमी ८:१२-१७, गलाती ५:१६-२५", "पवित्र आत्माको सामर्थ्य र चरित्रमा हिँड्ने जीवन"),
        SermonPreset("ख्रीष्टियान पारिवारिक एकता (Family in Christ)", "यहोशू २४:१४-१५, एफिसी ५:२१-३३", "ख्रीष्ट केन्द्रित परिवार: प्रेम, आदर र ईश्वरीय आशिषको घर"),
        SermonPreset("सङ्कष्टमा जीवित आशा (Living Hope in Trials)", "१ पत्रुस १:३-९, रोमी ८:२८-३९", "जीवनका आँधीबेहरीहरूमा ख्रीष्टमा भएको अटल आशा"),
        SermonPreset("अगौटे फल र उदारता (First Fruits & Giving)", "हितोपदेश ३:९-१०, २ कोरिन्थी ९:६-१५", "परमेश्वरको राज्यमा अगौटे फल र उदारताको ईश्वरीय आशिष")
    )

    val availableAudiences = listOf(
        "सम्पूर्ण मण्डली (Sunday Congregation)",
        "युवा सङ्गति (Youth Fellowship)",
        "परिवार तथा दम्पती (Families & Couples)",
        "मण्डलीका अगुवाहरू (Church Leaders & Elders)",
        "नयाँ विश्वासीहरू (New Believers & Seekers)"
    )

    val availableDurations = listOf(15, 30, 45, 60)

    fun generateSermon(topic: String, audience: String, durationMinutes: Int): SermonOutline {
        val selectedPreset = availableTopics.find { it.topicName.contains(topic, ignoreCase = true) }
            ?: availableTopics[0]

        val pointsCount = when {
            durationMinutes <= 20 -> 3
            durationMinutes <= 35 -> 3
            durationMinutes <= 45 -> 4
            else -> 5
        }

        val title = when (topic) {
            "विश्वासको विजय (Victory of Faith)" -> "चट्टानमाथि खडा हुने विश्वास: असम्भवलाई सम्भव बनाउने बाटो"
            "परमेश्वरको अनन्त अनुग्रह (Eternal Grace)" -> "अमूल्य अनुग्रह: हाम्रो योग्यताविना परमेश्वरको सित्तैँको वरदान"
            "प्रार्थनाको सामर्थ्य (Power of Prayer)" -> "निरन्तर प्रार्थना: जीवनका हरेक परीक्षामा अलौकिक शान्ति"
            "हृदयको साँचो क्षमा (Heartfelt Forgiveness)" -> "क्षमाको मुटु: जसरी ख्रीष्टले क्षमा गर्नुभयो, हामी पनि गरौं"
            "पवित्र आत्माको अगुवाइ (Led by the Spirit)" -> "आत्मामा हिँड्नु: नयाँ सामर्थ्य र पवित्र फल फलाउने जीवन"
            "ख्रीष्टियान पारिवारिक एकता (Family in Christ)" -> "म र मेरो घराना: परमप्रभुको सेवा गर्ने संयुक्त अठोट"
            "सङ्कष्टमा जीवित आशा (Living Hope in Trials)" -> "घोर अन्धकारमा चम्किने ज्योति: ख्रीष्टमा हाम्रो अटल आशा"
            else -> selectedPreset.defaultTitle
        }

        val mainPassage = selectedPreset.defaultPassage

        val intro = """
            प्रिय मण्डली परिवार तथा आदरणीय $audience! 
            आज हामी परमेश्वरको जीवित वचनबाट '$topic' भन्ने गम्भीर र जीवन-परिवर्तनकारी विषयमा अध्ययन गर्न गइरहेका छौं।
            यस $durationMinutes मिनेटको उपदेशमा हामी परमेश्वरको वचनलाई हाम्रो हृदयको ऐना बनाउनेछौं।
            संसारले हामीलाई निराशा, डर र चिन्ता दिन सक्छ, तर हाम्रो पवित्रशास्त्रले जीवनको हरेक आँधीमा स्थिर रहने अचूक ज्योति र मार्गदर्शन प्रदान गर्दछ।
        """.trimIndent()

        val mainPoints = when (topic) {
            "विश्वासको विजय (Victory of Faith)" -> listOf(
                "१. विश्वासको जग: आफ्नै बुझाइमा होइन, परमेश्वरको अनन्त वचनमा भर पर्नु (हितोपदेश ३:५)।",
                "२. विश्वासको परीक्षा: सुनलाई आगोमा खारेजस्तै कठिनाइहरूले विश्वासलाई सिद्ध बनाउँछन् (१ पत्रुस १:७)।",
                "३. विश्वासको कदम: जहाँ आँखाले देख्न सक्दैन, त्यहाँ परमेश्वरको प्रतिज्ञामा हिँड्नु (२ कोरिन्थी ५:७)।",
                if (pointsCount >= 4) "४. विश्वासको विजय: ख्रीष्टमाथि भरोसा राख्नेहरू कहिल्यै लज्जित हुनुपर्दैन (रोमी १०:११)।" else "",
                if (pointsCount >= 5) "५. विश्वासको निरन्तरता: अन्त्यसम्म विश्वासको दौड इमानदारीपूर्वक पूरा गर्नु (२ तिमोथी ४:७)।" else ""
            ).filter { it.isNotBlank() }

            "प्रार्थनाको सामर्थ्य (Power of Prayer)" -> listOf(
                "१. प्रार्थनाको आत्मीयता: परमेश्वरलाई पिताको रूपमा पुकार्ने सम्बन्ध (मत्ती ६:९)।",
                "२. प्रार्थनाको भरोसा: कुनै कुराको चिन्ता नगरी धन्यवादसहित मागहरू राख्नु (फिलिप्पी ४:६)।",
                "३. प्रार्थनाको शक्ति: धर्मी जनको हार्दिक प्रार्थनाले परिस्थिति परिवर्तन गर्छ (याकूब ५:१६)।",
                if (pointsCount >= 4) "४. प्रार्थनाको पर्खाइ: परमेश्वरको उत्तम समय र इच्छामा आत्मसमर्पण (लूका १८:१)।" else "",
                if (pointsCount >= 5) "५. मध्यस्थताको जिम्मेवारी: अरूको उद्धार र छुटकाराका निम्ति प्रार्थनाको पर्खाल बन्नु (इजकिएल २२:३०)।" else ""
            ).filter { it.isNotBlank() }

            else -> listOf(
                "१. ईश्वरीय सत्यको पहिचान: परमेश्वरको वचनअनुसार जीवनको वास्तविक अवस्था बुझ्नु।",
                "२. हृदयको समर्पण: पुरानो पापमय र स्वार्थी स्वभावलाई ख्रीष्टको पाउमा बिसाउनु।",
                "३. दैनिक जीवनमा आज्ञाकारिता: केवल वचन सुन्ने मात्र नभई त्यसलाई पालन गर्ने कर्ता बन्नु।",
                if (pointsCount >= 4) "४. मण्डली र समाजमा ख्रीष्टको गवाही: ज्योति र नुनजस्तै समाजलाई असल प्रभाव पार्नु।" else "",
                if (pointsCount >= 5) "५. अनन्त राज्यको दृष्टिकोण: यस क्षणिक संसारभन्दा माथि स्वर्गको अनन्त आशामा नजर राख्नु।" else ""
            ).filter { it.isNotBlank() }
        }

        val detailedExplanations = """
            हामीले अध्ययन गरेका मुख्य बुँदाहरूलाई नियाल्दा:
            पहिलो बुँदाले हामीलाई परमेश्वरसँगको सही सम्बन्धमा बाँध्छ। हामी आफ्नै योग्यता, बुद्धि वा आर्थिक हैसियतले बाँचेका छैनौं, तर परमेश्वरको निरन्तर अनुग्रहमा टिकेका छौं।
            दोस्रो बुँदाले परीक्षाको घडीमा विश्वासीले कस्तो आत्मिक अडान लिनुपर्छ भनी स्पष्ट पार्छ। जीवनमा कठिनाइ आउनु परमेश्वरले छोड्नुभएको प्रमाण होइन, तर उहाँले हामीलाई अझ परिपक्व बनाउँदै हुनुहुन्छ भन्ने प्रमाण हो।
            तेस्रो बुँदाले हामीलाई व्यावहारिक जीवनतर्फ डोऱ्याउँछ। मण्डलीको ढोकाबाट बाहिर निस्किएपछि हाम्रो बोली, व्यवहार, व्यापार, र परिवारमा ख्रीष्टको स्वभाव देखिनुपर्छ।
        """.trimIndent()

        val supportingVerses = listOf(
            mainPassage,
            "भजनसंग्रह ११९:१०५",
            "२ तिमोथी ३:१६-१७",
            "यूहन्ना १४:२७",
            "रोमी ८:३१"
        )

        val biblicalExamples = """
            बाइबलीय उदाहरण:
            १. अब्राहामले परमेश्वरको आवाज सुनेर आफ्नो देश र कुटुम्ब छोडी विश्वासका साथ यात्रा सुरु गरे (उत्पत्ति १२)।
            २. दानिएलले सिंहको खोरको सामना गर्नुपर्दा पनि दिनको तीन पटक धन्यवादसहित प्रार्थना गरिरहे। परमेश्वरले सिंहहरूको मुख बन्द गरिदिनुभयो (दानिएल ६)।
            ३. दाऊदले विशाल गोल्यतको अगाडि तरवार र भालाले होइन, तर सेनाहरूका परमप्रभुको नाउँमा उभिएर असम्भव देखिने विजय प्राप्त गरे (१ शमूएल १७)।
        """.trimIndent()

        val modernExamples = """
            आधुनिक जीवनको उदाहरण:
            आजको व्यस्त र प्रतिस्पर्धात्मक संसारमा हामी धेरै पटक मानसिक तनाव, आर्थिक संकट र सम्बन्धका उतारचढावहरूबाट गुज्रिरहेका हुन्छौं।
            जसरी एउटा मोबाइल फोन चार्ज नगरी बन्द हुन्छ, त्यसरी नै जब विश्वासीले प्रार्थना र वचनको चार्ज लिन छोड्छ, उसको आत्मिक जीवन कमजोर बन्दछ।
            जब हामी दैनिक जीवनका साना-साना निर्णयहरूमा पनि ख्रीष्टलाई पहिलो स्थान दिन्छौं, परमेश्वरले हाम्रो परिवार र काममा शान्ति र आशिष खन्याउनुहुन्छ।
        """.trimIndent()

        val practicalApplications = """
            व्यावहारिक प्रयोगहरू ($audience का निम्ति):
            १. दैनिक व्यक्तिगत समय: हरेक बिहान कम्तीमा १५ मिनेट वचन अध्ययन र प्रार्थनाको समय निश्चित गर्नुहोस्।
            २. बोली र व्यवहारमा शुद्धता: घरमा, कार्यक्षेत्रमा वा मण्डलीमा नकारात्मक आलोचना र गनगन बन्द गरी आशिषका शब्दहरू बोल्नुहोस्।
            ३. खाँचोमा परेकाहरूको सेवा: यसै हप्ता आफ्नो मण्डली वा छिमेकमा कुनै निराश वा बिरामी व्यक्तिलाई भेटेर प्रार्थना र सहयोग गर्नुहोस्।
            ४. निरन्तर संगति: मण्डलीको संगति र घरेलु प्रार्थनामा नियमित उपस्थित हुनुहोस्।
        """.trimIndent()

        val conclusion = """
            निष्कर्ष:
            परमेश्वरको प्रिय जनहरू, आजको वचन हाम्रा कानले मात्र सुन्ने शब्दहरू होइनन्, तर हाम्रो जीवन बदल्ने ईश्वरीय शक्ति हो।
            यदि तपाईं आज कमजोर वा निराश महसुस गर्दै हुनुहुन्छ भने, याद राख्नुहोस् कि ख्रीष्टले तपाईंको निम्ति क्रूसमा सबै मूल्य चुक्ता गरिसक्नुभएको छ।
            आउनुहोस्, हामी आफ्ना सबै संशय, चिन्ता र भारीहरू येशूको पाउमा समर्पण गरौं र उहाँको विजयमा अघि बढौं।
        """.trimIndent()

        val closingPrayer = """
            समापन प्रार्थना:
            सर्वशक्तिमान्, करुणामय स्वर्गीय पिता परमेश्वर!
            आज तपाईंको पवित्र र जीवित वचन हाम्रा सामु प्रकट गरिदिनुभएकोमा हामी तपाईंलाई कोटी-कोटी धन्यवाद चढाउँदछौं।
            हामीले सुनेका यी जीवनदायी वचनहरू हाम्रो हृदयको उर्वर भूमिमा रोपिन सकून् र तीस गुणा, साठी गुणा र सय गुणा फल फलाउन सकून्।
            उपस्थित प्रत्येक $audience लाई तपाईंको स्वर्गीय शान्ति, सुरक्षा र नयाँ सामर्थ्यले अभिषेक गर्नुहोस्।
            हाम्रा पाइलाहरू सधैँ तपाईंको सत्यको बाटोमा स्थिर रहून्।
            सबै आदर, महिमा र प्रशंसा केवल तपाईंलाई चढाउँदै,
            यो प्रार्थना जीवित मुक्तिदाता प्रभु येशू ख्रीष्टको अति पवित्र र सामर्थी नाउँमा माग्दछौं, आमेन!
        """.trimIndent()

        return SermonOutline(
            title = title,
            topic = topic,
            targetAudience = audience,
            durationMinutes = durationMinutes,
            mainPassage = mainPassage,
            introduction = intro,
            mainPoints = mainPoints,
            detailedExplanations = detailedExplanations,
            supportingVerses = supportingVerses,
            biblicalExamples = biblicalExamples,
            modernExamples = modernExamples,
            practicalApplications = practicalApplications,
            conclusion = conclusion,
            closingPrayer = closingPrayer
        )
    }
}
